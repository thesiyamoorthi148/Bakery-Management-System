USE Bakery;

CREATE TABLE REVIEW(
    REVIEW_ID INT PRIMARY KEY,
    PRODUCT_ID INT,
    CUSTOMER_NAME VARCHAR(25),
    REVIEW_TEXT VARCHAR(20),
    REVIEW_DATE DATE
);

CREATE TABLE RATING(
      RATING_ID INT PRIMARY KEY,
      REVIEW_ID INT,
      RATING INT,
      FOREIGN KEY (REVIEW_ID) REFERENCES REVIEW(REVIEW_ID)
);

