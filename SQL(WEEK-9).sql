USE Bakery;

SELECT COUNT(*)AS TOTAL_PRODUCTS
FROM Product;

SELECT SUM(TOTAL_PRICE) AS TOTAL_SALES
FROM Ordertable;

SELECT AVG(TOTAL_PRICE) AS AVERAGE_SALES
FROM Ordertable;

SELECT
MIN(TOTAL_PRICE) AS MINIMUM_SALES,
MAX(TOTAL_PRICE) AS MAXIMUM_SALES
FROM Ordertable;

SELECT ORDER_ID,
CUSTOMER_NAME,
QUANTITY,
TOTAL_PRICE,
ORDER_STATUS
FROM Ordertable;

SELECT CUSTOMER_NAME,
SUM(TOTAL_PRICE) AS PURCHASE_AMOUNT
FROM Ordertable
GROUP BY CUSTOMER_NAME
ORDER BY PURCHASE_AMOUNT DESC
LIMIT 5;

SELECT Product.ProductID,
Product.ProductName,
SUM(ORDERDETAIL.PRODUCT_QUANTITY) AS TOTAL_SOLD
FROM Product
JOIN ORDERDETAIL
ON Product.ProductID = ORDERDETAIL.ProductID
GROUP BY  Product.ProductID,
Product.ProductName
ORDER BY TOTAL_SOLD DESC;

SELECT Category.CategoryName,
SUM(ORDERDETAIL.PRODUCT_QUANTITY) AS TOTAL_QUANTITY,
SUM(ORDERDETAIL.PRODUCT_QUANTITY * ORDERDETAIL.UNIT_PRICE) AS TOTAL_SALES
FROM Category
JOIN Product 
ON Category.CategoryID = Product.CategoryID
JOIN ORDERDETAIL
ON Product.ProductID = ORDERDETAIL.ProductID
GROUP BY Category.CategoryID,
Category.CategoryName
ORDER BY TOTAL_SALES DESC;

SELECT SUM(PRODUCT_QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM ORDERDETAIL;

SELECT Product.ProductID,
Product.ProductName,
SUM(ORDERDETAIL.PRODUCT_QUANTITY * ORDERDETAIL.UNIT_PRICE) AS SALES_AMOUNT
FROM Product
JOIN ORDERDETAIL
ON Product.ProductID = ORDERDETAIL.ProductID
GROUP BY Product.ProductID,
Product.ProductName
ORDER BY SALES_AMOUNT DESC;